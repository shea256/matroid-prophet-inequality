#!/usr/bin/env python3
"""Assemble the selected written result and regenerate stable paper entry points.

--markdown-only updates text/metadata, leaving the PDF stale until rebuilt.
--check is read-only and needs only Python; it verifies generated text and the
recorded input, LaTeX, and PDF hashes. Full builds require Pandoc and pdfLaTeX.
"""
import argparse
from fractions import Fraction
import hashlib
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import tempfile
from urllib.parse import urlsplit

from result_registry import ROOT, CERTIFICATE_FIELDS, load, local_path


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def tex_fraction(value):
    q = Fraction(value)
    return str(q.numerator) if q.denominator == 1 else rf'\frac{{{q.numerator}}}{{{q.denominator}}}'


def rebase(text, source, root):
    """Fragments use normal relative Markdown links; assembled links use root."""
    def replace(match):
        target = match.group(2).strip('<>')
        url = urlsplit(target)
        if url.scheme or url.netloc or not url.path:
            return match.group(0)
        dest = (root/source).parent/url.path
        name = dest.resolve().relative_to(root.resolve()).as_posix()
        if url.fragment:
            name += '#'+url.fragment
        return match.group(1)+name+match.group(3)
    return re.sub(r'(!?\[[^\]]*\]\()([^\n)]+)(\))', replace, text)


def history_table(registry):
    rows = ['| Result | Guarantee | Change | Review stage |',
            '|---|---:|---|---|']
    for r in registry['results']:
        guarantee = '$>2^{-'+str(r['exponent'])+'}$' if r['status'] != 'candidate' else 'Unselected candidate'
        review = 'Written proof; independent review pending' if r['status'] != 'candidate' else 'Incomplete'
        rows.append(f"| [{r['title']}]({r['record']}) | {guarantee} | {r['change']} | {review} |")
    return '\n'.join(rows)


def generated(root=ROOT):
    registry, current, cert = load(root)
    coefficient = Fraction(current['coefficient'])
    predecessors = [r for r in registry['results'] if r['status'] != 'candidate'
                    and r['id'] != current['id'] and Fraction(r['coefficient']) < coefficient]
    previous = max(predecessors, key=lambda r: Fraction(r['coefficient'])) if predecessors else None
    gain = float(coefficient/Fraction(previous['coefficient'])) if previous else None
    review = 'Written proof with same-agent verification; independent mathematical review and formalization pending.'
    exp, seed = current['exponent'], cert['seed_bits']
    formula = rf'C_\star={tex_fraction(coefficient)}>2^{{-{exp}}}'
    previous_text = (f"The exact certificate is approximately **{gain:.5f} times** the preceding "
                     f"[`2^-{previous['exponent']}` certificate]({previous['record']}). "
                     'This compares guaranteed fractions, not measured performance.' if previous else '')
    front = f'''# {registry['paper_title']}

**{', '.join(registry['authors'])}**

{current['date']}. Selected result: **{current['title']}**.

<!-- Generated by scripts/build_manuscript.py. Edit paper/ and results/, not this file. -->
<!-- paper-body -->

**{review}**

{current['change']} The paper states the construction and source interfaces,
proves the shared lemmas, and derives the selected coefficient below.

## Current theorem and dependencies

For every known finite labeled matroid $M$ on $n$ elements, there is a
measurable, distribution-independent online rule using one independent
sample per label and ${seed}$ initial independent fair bits. All sample/value
coordinates are mutually independent and nonnegative, with matching laws
at each label, and the seed is independent. Assume only that
$\mathbb E[\operatorname{{OPT}}_M(V)]<\infty$. For every measurable arrival
permutation depending on all samples, all values, and the entire seed,
the accepted set is independent after every prefix and

$$
\mathbb E[\mathrm{{reward}}]\ge C_\star\mathbb E[\operatorname{{OPT}}_M(V)],\qquad
{formula}.
$$

{previous_text}

We retain the density paths, generators, hybrid safety comparison, marked-pivot
machinery, rank accounting, and lossless simulation from
[OpenAI's pinned manuscript](https://github.com/openai/math/blob/{registry['source_commit']}/preprints/One-Sample-Suffices-for-Matroid-Prophet-Inequalities-against-an-Almighty-Adversary-September-23-2026/final.pdf).
Their interfaces are specified below. Computation and storage may be
exponential, with exact observations; no polynomial-time claim is made.

'''
    sections = [registry['framework'], current['record'], registry['attribution']]
    body = '\n\n'.join(rebase(local_path(root, name).read_text().rstrip(), name, root) for name in sections)
    table = history_table(registry)
    history = '\n\n## Development history\n\n'+table+'\n\nEarlier results retain their original evidence and source credit. These are\nstages of one research effort, not independent priority claims. Preserved\npublications are indexed in [the archive](archive/README.md).\n'
    manuscript = front+body+history
    current_meta = dict(result_id=current['id'], title=current['title'], authors=registry['authors'],
                        date=current['date'], review_status=review,
                        independent_review_completed=current['independent_review_completed'],
                        lean_formalization_completed=current['formalization_completed'],
                        **{key: cert[key] for key in CERTIFICATE_FIELDS},
                        certificate=current['certificate'], registry='results/registry.json',
                        record=current['record'], paper='manuscript.pdf', proof='manuscript.md',
                        source_commit=registry['source_commit'],
                        novelty_status='Unresolved; no priority or confirmed best-known-bound claim')
    summary = f'''

**[Read the latest paper (PDF)](manuscript.pdf)** · [Read online](manuscript.md) · [LaTeX source](tex/manuscript.tex)

Current result: **[{current['title']}]({current['record']})**, {current['date']}.

```math
\mathbb E[\mathrm{{reward}}]\ge C_\star\mathbb E[\mathrm{{OPT}}],\qquad
{formula}.
```

{previous_text} The construction uses **`{seed}` fair bits**.

{current['change']}

**{review}** Finite checks accompany the written proof; they do not prove
its universal assertions. No priority or confirmed best-known-bound claim
is made. These paper links remain stable as results are updated.

'''
    readme = local_path(root, 'README.md').read_text()
    pattern = r'<!-- current-result:start -->.*?<!-- current-result:end -->'
    if len(re.findall(pattern, readme, re.S)) != 1:
        raise ValueError('README must contain one generated current-result block')
    readme = re.sub(pattern, lambda m: '<!-- current-result:start -->'+summary+'<!-- current-result:end -->', readme, flags=re.S)
    improvements = '# Improvement record\n\n<!-- Generated from results/registry.json. -->\n\n'+table+'\n\n'
    improvements += ('The registry explicitly selects `'+current['id']+'`. Historical records and\n'
                     'certificates remain unchanged. Review status and mathematical validity are\n'
                     'distinct: these records have written proofs and same-agent checks, with\n'
                     'independent review and formalization pending. No priority claim is made.\n\n')
    for r in registry['results']:
        improvements += f"## {r['date']} — {r['title']}\n\n{r['change']}\n\n[Result record]({r['record']})"
        if r['status'] != 'candidate':
            improvements += f" · [Certificate]({r['certificate']})"
        if 'archive' in r:
            improvements += f" · [Preserved publication]({r['archive']}/README.md)"
        improvements += '\n\n'
    result = f'''# Current result

<!-- Generated from results/registry.json and the selected certificate. -->

**Written theorem claim: a guarantee greater than `2^-{exp}`** in the original
one-sample, full-seed almighty-adversary model. The exact conservative
coefficient is `{current['coefficient']}`, with `{seed}` initial fair bits.

{previous_text}

{current['change']}

{review} The universal claim rests on the written argument and explicit source
dependencies; exact arithmetic and finite enumeration establish their stated
finite assertions. No polynomial-time, practical-performance, exhaustive
novelty, or confirmed strongest-known-bound claim is made.

- [Complete paper](manuscript.md) and [PDF](manuscript.pdf)
- [Selected argument]({current['record']}) and [exact certificate]({current['certificate']})
- [Verification scope](verification/README.md) and [run receipt](verification/current_run_receipt.json)
- [Baseline](BASELINE.md), [review questions](HANDOFF.md), and [history](IMPROVEMENTS.md)
'''
    return {'manuscript.md': manuscript, 'README.md': readme, 'IMPROVEMENTS.md': improvements.rstrip()+'\n',
            'RESULT.md': result, 'results/current.json': json.dumps(current_meta, indent=2)+'\n'}


def input_hashes(root=ROOT):
    registry, current, cert = load(root)
    names = {'results/registry.json', registry['framework'], registry['attribution'],
             current['record'], 'tex/preamble.tex', 'scripts/build_manuscript.py',
             'scripts/result_registry.py'}
    # The history is included in the paper, so bind every incorporated certificate.
    names.update(r['certificate'] for r in registry['results'] if r['status'] != 'candidate')
    return {name: digest(local_path(root, name)) for name in sorted(names)}


def verify_generated(root=ROOT):
    for name, expected in generated(root).items():
        if local_path(root, name).read_text() != expected:
            raise ValueError('Stale generated file: '+name+'; run scripts/build_manuscript.py')


def verify_build(root=ROOT):
    receipt = json.loads(local_path(root, 'verification/paper_build.json').read_text())
    if receipt.get('inputs') != input_hashes(root):
        raise ValueError('Paper input hashes changed; rebuild the PDF')
    for key, hash_key in (('pdf', 'sha256'), ('source', 'source_sha256'), ('markdown', 'markdown_sha256')):
        if digest(local_path(root, receipt[key])) != receipt[hash_key]:
            raise ValueError('Paper artifact hash mismatch: '+receipt[key])
    if local_path(root, receipt['pdf']).stat().st_size != receipt['bytes'] or receipt['warnings']:
        raise ValueError('Paper size/warnings differ from a clean build')
    return receipt


def render_tex(root, manuscript):
    registry, _, _ = load(root)
    body = manuscript.split('<!-- paper-body -->', 1)[1]
    # PDF links to repository files should work outside a cloned checkout.
    def absolute(match):
        target = match.group(2)
        if urlsplit(target).scheme or target.startswith('#'):
            return match.group(0)
        return match.group(1)+registry['repository']+'/blob/master/'+target+match.group(3)
    body = re.sub(r'(!?\[[^\]]*\]\()([^\n)]+)(\))', absolute, body)
    result = subprocess.run(['pandoc', '--from=markdown+tex_math_dollars', '--to=latex',
                             '--shift-heading-level-by=-1', '--wrap=none'], input=body,
                            text=True, stdout=subprocess.PIPE, stderr=subprocess.PIPE, check=True)
    def escape(s):
        return re.sub(r'([%&#_{}])', r'\\\1', s)
    return ('% Generated by scripts/build_manuscript.py; edit paper/ and results/.\n'
            '\\documentclass[11pt]{article}\n'+(root/'tex/preamble.tex').read_text()+
            '\\hypersetup{pdftitle={'+escape(registry['paper_title'])+'},pdfauthor={'+escape(', '.join(registry['authors']))+'}}\n'
            '\\title{'+escape(registry['paper_title'])+'}\n\\author{'+escape(', '.join(registry['authors']))+'}\n'
            '\\date{'+escape(load(root)[1]['date'])+'}\n\\begin{document}\n\\maketitle\n'+
            result.stdout+'\n\\end{document}\n')


def build(root=ROOT):
    for program in ('pandoc', 'pdflatex'):
        if not shutil.which(program):
            raise ValueError(program+' is required for a full build; see results/README.md')
    text = generated(root)
    tex = render_tex(root, text['manuscript.md'])
    env = dict(os.environ, SOURCE_DATE_EPOCH='1791590400', FORCE_SOURCE_DATE='1')
    with tempfile.TemporaryDirectory(prefix='matroid-paper-') as tmp:
        source = Path(tmp)/'manuscript.tex'
        source.write_text(tex)
        for _ in range(3):
            result = subprocess.run(['pdflatex', '-interaction=nonstopmode', '-halt-on-error',
                                     '-no-shell-escape', source.name], cwd=tmp, env=env,
                                    text=True, stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
            if result.returncode:
                raise ValueError(result.stdout)
        log = (Path(tmp)/'manuscript.log').read_text()
        warnings = [line for line in log.splitlines() if 'Warning' in line or 'Overfull' in line]
        if warnings:
            raise ValueError('Paper build warnings:\n'+'\n'.join(warnings))
        pdf = (Path(tmp)/'manuscript.pdf').read_bytes()
    # Publish outputs only after a successful, warning-free compile.
    for name, content in text.items():
        (root/name).write_text(content)
    (root/'tex/manuscript.tex').write_text(tex)
    (root/'manuscript.pdf').write_bytes(pdf)
    receipt = dict(pdf='manuscript.pdf', bytes=len(pdf), sha256=digest(root/'manuscript.pdf'),
                   source='tex/manuscript.tex', source_sha256=digest(root/'tex/manuscript.tex'),
                   markdown='manuscript.md', markdown_sha256=digest(root/'manuscript.md'),
                   passes=3, warnings=[], inputs=input_hashes(root),
                   pandoc=subprocess.check_output(['pandoc', '--version'], text=True).splitlines()[0])
    (root/'verification/paper_build.json').write_text(json.dumps(receipt, indent=2)+'\n')
    return receipt


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    flags = parser.add_mutually_exclusive_group()
    flags.add_argument('--check', action='store_true')
    flags.add_argument('--markdown-only', action='store_true')
    args = parser.parse_args()
    if args.check:
        verify_generated()
        verify_build()
        print('PASS generated text, registry/certificates, and paper input/artifact hashes')
    elif args.markdown_only:
        for name, content in generated().items():
            (ROOT/name).write_text(content)
        print('Updated generated text and metadata; rebuild the PDF before handoff.')
    else:
        result = build()
        print('Rebuilt manuscript, LaTeX, PDF, current metadata, README headline, and history ('+str(result['bytes'])+' PDF bytes).')


if __name__ == '__main__':
    main()
